"""Exact, shared-label changed-bond evaluation on fully resolved inputs.

The exhaustive full-reactant symmetry route is a bounded development oracle.
It raises on incomplete symmetry rather than silently reporting exact scores.
Production callers must also establish minimum and label-enumeration closure.
"""

from dataclasses import dataclass
from fractions import Fraction
from time import monotonic

import networkx as nx

from .identifiability import Endpoint


class IncompleteSymmetry(RuntimeError):
    """The full attributed automorphism group was not established."""


def _graph(endpoint):
    graph = nx.Graph()
    for i, z in enumerate(endpoint.atomic_numbers):
        graph.add_node(i, color=(z, endpoint.charges[i], endpoint.hcounts[i]))
    for i, j, order in endpoint.bonds:
        graph.add_edge(i, j, order=order)
    return graph


def full_automorphisms(endpoint: Endpoint, *, max_automorphisms=100000,
                       time_limit_seconds=30):
    """Enumerate all symmetries, preserving elements, charges, H and orders.

    The time check is cooperative between matcher yields; a campaign runner
    still needs an external process deadline. Component roles are not supported
    by this contract and must not be claimed as preserved attributes.
    """
    if max_automorphisms < 1 or time_limit_seconds <= 0:
        raise ValueError("Symmetry limits must be positive")
    graph = _graph(endpoint)
    matcher = nx.algorithms.isomorphism.GraphMatcher(
        graph, graph,
        node_match=nx.algorithms.isomorphism.categorical_node_match("color", None),
        edge_match=nx.algorithms.isomorphism.categorical_edge_match("order", None),
    )
    start = monotonic()
    permutations = []
    for mapping in matcher.isomorphisms_iter():
        if monotonic() - start > time_limit_seconds:
            raise IncompleteSymmetry("Automorphism deadline exceeded")
        if len(permutations) >= max_automorphisms:
            raise IncompleteSymmetry("Automorphism output cap exceeded")
        permutations.append(tuple(mapping[i] for i in range(len(graph))))
    if monotonic() - start > time_limit_seconds:
        raise IncompleteSymmetry("Automorphism deadline exceeded")
    return tuple(sorted(permutations))


def bond_f1(prediction, label):
    prediction, label = frozenset(prediction), frozenset(label)
    denominator = len(prediction) + len(label)
    return Fraction(2 * len(prediction & label), denominator) if denominator else Fraction(1)


def transport_bonds(label, permutation):
    return frozenset(tuple(sorted((permutation[i], permutation[j]))) for i, j in label)


@dataclass(frozen=True)
class ScoreWitness:
    score: Fraction
    transporter: tuple[int, ...]


class ExactBondEvaluator:
    """Scorer bound to one endpoint and its completely enumerated symmetry."""

    def __init__(self, reactant: Endpoint, **symmetry_limits):
        self.n = len(reactant.atomic_numbers)
        self.automorphisms = full_automorphisms(reactant, **symmetry_limits)

    def _validate(self, bonds):
        bonds = frozenset(bonds)
        if any(len(pair) != 2 or not 0 <= pair[0] < pair[1] < self.n for pair in bonds):
            raise ValueError("Bond labels require canonical in-range unordered pairs")
        return bonds

    def score(self, prediction, label):
        prediction, label = self._validate(prediction), self._validate(label)
        best = None
        for permutation in self.automorphisms:
            score = bond_f1(prediction, transport_bonds(label, permutation))
            if best is None or score > best.score:
                best = ScoreWitness(score, permutation)
        return best

    def orbit_key(self, label):
        label = self._validate(label)
        return min(tuple(sorted(transport_bonds(label, p))) for p in self.automorphisms)

    def paired_envelope(self, prediction_a, prediction_b, labels, *, labels_complete):
        """Return attained min/max differences with shared candidate witnesses.

        ``labels_complete`` is an explicit caller obligation, not a proof
        generated by the scorer. An incomplete set is refused by this API.
        """
        if not labels_complete:
            raise ValueError("Exact envelopes require complete admitted labels")
        values = []
        for label in labels:
            label = self._validate(label)
            a, b = self.score(prediction_a, label), self.score(prediction_b, label)
            values.append(PairedWitness(a.score - b.score, label, a, b))
        if not values:
            raise ValueError("At least one admitted label is required")
        return min(values, key=lambda x: x.difference), max(values, key=lambda x: x.difference)


@dataclass(frozen=True)
class PairedWitness:
    difference: Fraction
    label: frozenset[tuple[int, int]]
    a: ScoreWitness
    b: ScoreWitness
