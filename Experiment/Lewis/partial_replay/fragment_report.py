"""Verify a completed fragment-replay run and generate manuscript tables."""

import argparse
from collections import Counter, defaultdict
import gzip
import json
from pathlib import Path

from .benchmark import digest
from .fragment_metrics import METRICS


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("run", type=Path)
    args = parser.parse_args()
    run = args.run
    summary = json.loads((run / "summary.json").read_text())
    assert digest(run / "records.jsonl.gz") == summary["records_sha256"]
    assert summary["source_unchanged"]
    statuses, examples, totals, rejected_rows = Counter(), defaultdict(list), defaultdict(Counter), Counter()
    row_count = 0
    for line in gzip.open(run / "records.jsonl.gz", "rt"):
        record = json.loads(line)
        row_count += 1
        statuses[record["status"]] += 1
        for mode, directions in record.get("runs", {}).items():
            for direction, values in directions.items():
                key = mode + "/" + direction
                for metric in METRICS:
                    totals[key][metric] += values[metric]
                if values.get("rejected_partial_completions"):
                    rejected_rows[key] += 1
                if values["status"] == "complete":
                    assert not values["exact_set"] or values["all_gt_molecules"]
                    assert not values["all_gt_molecules"] or values["largest_gt_recovered"]
                    assert not values["max_fragment_match"] or values["largest_gt_recovered"]
                    assert not values["largest_gt_recovered"] or values["any_gt_molecule"]
                    label = key + ("/largest_only" if values["largest_gt_recovered"] and not values["all_gt_molecules"]
                                   else "/extra_outputs" if values["all_gt_molecules"] and not values["exact_set"]
                                   else "/miss" if not values["largest_gt_recovered"] else "/exact")
                else:
                    assert not any(values[metric] for metric in METRICS)
                    label = key + "/" + values["status"]
                if len(examples[label]) < 10:
                    examples[label].append({"r_id": record["r_id"], "target": record["targets"][direction],
                                            "outcome_sample": values.get("outcome_sample", []),
                                            "error": values.get("error")})
    assert row_count == summary["rows"]
    for key, metrics in totals.items():
        assert all(metrics[m] == summary["metrics"][key][m] for m in METRICS)
    evidence = {"schema": "synkit.fragment-replay-check/1", "source_rows": row_count,
                "record_status": dict(statuses), "summary_sha256": digest(run / "summary.json"),
                "script_sha256": digest(__file__), "rows_with_rejected_partial_completions": dict(rejected_rows),
                "examples": dict(examples), "record_totals_agree": True, "metric_implications_checked": True}
    (run / "analysis.json").write_text(json.dumps(evidence, indent=2, sort_keys=True) + "\n")
    table = [r"\begin{tabular}{@{}llrrrrr@{}}", r"\toprule",
             r"Match mode & Direction & Exact set & All GT & Any GT & GT largest & Max fragment\\", r"\midrule"]
    definitions = {"FragmentRows": row_count,
                   "FragmentRejectedCompletions": summary["metrics"]["partial/fw"].get("rejected_partial_completions", 0)}
    for mode in ("full", "partial"):
        for direction in ("fw", "bw"):
            key = mode + "/" + direction
            values = summary["metrics"][key]
            table.append(f"{mode.title()} & {direction.upper()} & " + " & ".join(f"{values.get(m,0):,}" for m in METRICS) + r"\\")
            for metric, suffix in (("exact_set", "Exact"), ("all_gt_molecules", "All"),
                                   ("any_gt_molecule", "Any"), ("largest_gt_recovered", "Largest"),
                                   ("max_fragment_match", "Max"), ("complete", "Complete")):
                definitions["Fragment" + mode.title() + direction.title() + suffix] = values.get(metric, 0)
    table += [r"\bottomrule", r"\end{tabular}"]
    (run / "table.tex").write_text("\n".join(table) + "\n")
    (run / "values.tex").write_text("% Generated by fragment_report.py\n" + "".join(
        "\\newcommand{\\" + key + "}{" + f"{value:,}" + "}\n" for key, value in definitions.items()))
    print(json.dumps({"rows": row_count, "rows_with_rejected_partial_completions": dict(rejected_rows),
                      "metrics": summary["metrics"], "errors": summary["errors"]}, indent=2))


if __name__ == "__main__":
    main()
