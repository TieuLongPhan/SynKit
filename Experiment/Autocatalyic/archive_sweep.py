"""Run the archived Higgs--Blackmond sweep programs and compare with the model.

The two archived C programs are compiled and run without modification. Each
integrates 201 preference ratios to t = 1e5 and then bisects the instability
threshold. The same sweep is repeated with the reaction-list model of this
study, from the same initial condition. Each archived run takes a few
minutes, and its output is cached in ``AUTOCAT_ARCHIVE_WORK``. Run from the
repository root::

    PYTHONDONTWRITEBYTECODE=1 python Experiment/Autocatalyic/archive_sweep.py
"""
from __future__ import annotations

import csv
import json
import os
import subprocess
from dataclasses import replace
from multiprocessing import Pool
from pathlib import Path

import numpy as np
from scipy.integrate import solve_ivp

from models import ParentParameters, parent, reference_initial

HERE = Path(__file__).resolve().parent
RESULTS = HERE/"results"
PAPER = HERE.parents[1]/"paper"/"autocatalytic"
WORK = Path(os.environ.get("AUTOCAT_ARCHIVE_WORK", "/tmp/synkit-autocatalytic-archive"))
PROGRAMS = {"constructive": "generalf", "destructive": "generalb"}
BASE = {"constructive": ParentParameters("constructive", k1=0.0, k2=0.75),
        "destructive": ParentParameters("destructive", k1=10.0, k2=0.0)}
HORIZON = 1e5


def archived_output(mechanism):
    WORK.mkdir(parents=True, exist_ok=True)
    name = PROGRAMS[mechanism]
    out = WORK/f"{name[-1]}.out"
    if not out.exists() or "eemon" not in out.read_text():
        binary = WORK/name
        subprocess.run(["/usr/bin/gcc", "-O2", "-w", "-o", str(binary),
                        str(HERE/"reference"/f"{name}.c"), "-lm"], check=True)
        with out.open("w") as handle:
            subprocess.run([str(binary)], stdout=handle, check=True)
    return out.read_text().splitlines()


def parse(lines):
    start = next(i for i, line in enumerate(lines) if line.startswith("k P L D LL LD"))
    table = []
    for line in lines[start+1:]:
        parts = line.split()
        if len(parts) != 10:
            break
        table.append([float(v) for v in parts])
    bisection = [line.split() for line in lines[start+1+len(table):] if len(line.split()) == 2]
    return np.array(table), float(bisection[-1][0])


def ours(args):
    mechanism, ratio = args
    base = BASE[mechanism]
    p = (replace(base, k1=base.k2*ratio) if mechanism == "constructive"
         else replace(base, k2=base.k1*ratio))
    model = parent(p)
    sol = solve_ivp(model.rhs, (0, HORIZON), reference_initial(1e-4), method="BDF",
                    jac=model.jacobian, rtol=1e-10, atol=1e-13)
    if not sol.success:
        raise RuntimeError(sol.message)
    return sol.y[:, -1]


def main():
    summary, values = {}, {}
    with Pool(int(os.environ.get("AUTOCAT_WORKERS", "8"))) as pool:
        for mechanism in PROGRAMS:
            table, threshold = parse(archived_output(mechanism))
            states = np.array(pool.map(ours, [(mechanism, r) for r in table[:, 0]]))
            # The printed ee is undefined when a monomer has decayed to zero.
            total = states[:, 1]+states[:, 2]
            ee = np.divide(states[:, 1]-states[:, 2], total, out=np.zeros_like(total),
                           where=total > 1e-12)
            archived_ee = np.nan_to_num(table[:, 8])
            fixed = BASE[mechanism].k2 if mechanism == "constructive" else BASE[mechanism].k1
            rows = [{"ratio": r, "archived_ee": a, "model_ee": e,
                     "largest_concentration_difference": float(np.max(np.abs(c-s)))}
                    for r, a, e, c, s in zip(table[:, 0], archived_ee, ee, table[:, 1:8], states)]
            with (RESULTS/f"archive_sweep_{mechanism}.csv").open("w", newline="") as handle:
                writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
                writer.writeheader()
                writer.writerows(rows)
            summary[mechanism] = {
                "ratios": len(rows), "horizon": HORIZON,
                "archived_threshold_ratio": threshold/fixed,
                "largest_ee_difference": float(np.max(np.abs(archived_ee-ee))),
                "largest_concentration_difference": max(
                    r["largest_concentration_difference"] for r in rows),
                "printed_digits": 6}
            print(mechanism, summary[mechanism], flush=True)
    (RESULTS/"archive_sweep.json").write_text(json.dumps(summary, indent=2)+"\n")
    con, des = summary["constructive"], summary["destructive"]
    values = {"ArchiveConRatios": con["ratios"], "ArchiveDesRatios": des["ratios"],
              "ArchiveConThreshold": f"{con['archived_threshold_ratio']:.4f}",
              "ArchiveDesThreshold": f"{des['archived_threshold_ratio']:.4f}",
              "ArchiveEEDiff": f"{max(con['largest_ee_difference'], des['largest_ee_difference']):.1e}",
              "ArchiveConcDiff": f"{max(con['largest_concentration_difference'], des['largest_concentration_difference']):.1e}"}
    lines = ["% Generated by Experiment/Autocatalyic/archive_sweep.py; do not edit."]
    lines += [rf"\newcommand{{\{k}}}{{{v}}}" for k, v in values.items()]
    (PAPER/"archive_results.tex").write_text("\n".join(lines)+"\n")


if __name__ == "__main__":
    main()
