    c.head(5.05, -0.08, "B", "Enumerate")
    c.head(11.20, -0.08, "C", "Classify")
    for k in range(2):
        pts = shift(
            [(0, 0), (0.3, 0.35), (0.6, 0), (0.9, 0.35), (1.2, 0)],
            0.45 + 2.15 * k,
            -1.6,
        )
        key = "reactant_edges" if k == 0 else "product_edges"
        graph(c, pts, [(i, j, 1, 1) for i, j in toy[key]])
        c.text(1.05 + 2.15 * k, -2.35, "$R$" if k == 0 else "$P$", "synsmall")
    c.line((1.82, -1.60), (2.40, -1.60), "synflow")
    c.text(2.1, -3.30, r"$\Omega(R,P),\quad C\;\mathrm{or}\;C^*$", "synlabel")
