"""Vector drawing layer; scientific results are supplied by the audited runners.

Chemical conventions follow thesis Chapters 03 and 10. Endpoint bonds and ITS
states come directly from frozen adjacency matrices, never from drawn geometry.
"""

from itertools import combinations
from math import cos, sin, pi, hypot, log10
from pathlib import Path

FIGURES = Path(__file__).resolve().parents[1] / "paper/synister/figures"


class Canvas:
    def __init__(self, height):
        self.lines = [
            r"% Generated by scripts/synister_diagrams.py.",
            r"\begin{tikzpicture}[x=1cm,y=1cm]",
            r"\syndesign{16}",
            rf"\path[use as bounding box] (0,.05) rectangle (16,-{height});",
        ]

    def add(self, line):
        self.lines.append(line)

    def text(self, x, y, text, style="synlabel"):
        self.add(rf"\node[{style}] at ({x:.3f},{y:.3f}) {{{text}}};")

    def head(self, x, y, letter, title):
        self.add(rf"\synpanelhead{{{x},{y}}}{{{letter}}}{{{title}}}")

    def line(self, p, q, style="synbond"):
        self.add(rf"\draw[{style}] ({p[0]:.3f},{p[1]:.3f}) -- ({q[0]:.3f},{q[1]:.3f});")

    def dot(self, x, y, color="npgBlue", radius=0.065):
        self.add(rf"\fill[{color}] ({x:.3f},{y:.3f}) circle ({radius});")

    def save(self, name):
        (FIGURES / name).write_text(
            "\n".join(self.lines + [r"\end{tikzpicture}"]) + "\n"
        )


def graph(c, coords, states, atoms=None, ids=None, paired=False, node_numbers=False, active_atoms=None):
    """Skeletal molecules or paired graphs; each node/edge remains data-backed."""
    for i, (name, _, _) in (ids or {}).items():
        x, y = coords[i]
        color = "npgBlue" if name == "a" else "npgPurple"
        c.add(
            rf"\filldraw[fill={color}!9,draw={color}!60,line width=.55pt] ({x},{y}) circle (.245);"
        )
    for i, j, before, after in states:
        p, q = coords[i], coords[j]
        style = "synbond"
        if active_atoms is not None and not {i, j} <= set(active_atoms):
            style += ',opacity=.23'
        if paired:
            style = (
                "synbond,draw=figMuted!75"
                if before == after
                else ("synbroken" if after == 0 else "synformed")
            )
        order = max(before, after)
        assert order in (1, 2) and (before == after or min(before, after) == 0)
        if order == 1:
            c.line(p, q, style)
        else:
            length = hypot(q[0] - p[0], q[1] - p[1])
            dx, dy = -(q[1] - p[1]) / length * 0.035, (q[0] - p[0]) / length * 0.035
            for sign in (-1, 1):
                c.line(
                    (p[0] + sign * dx, p[1] + sign * dy),
                    (q[0] + sign * dx, q[1] + sign * dy),
                    style,
                )
    hcl = (
        []
        if paired or atoms is None
        else [
            i
            for i, atom in enumerate(atoms)
            if atom["element"] == "Cl" and atom["hydrogens"] == 1
        ]
    )
    if len(hcl) == 2:
        assert not any(i in hcl or j in hcl for i, j, _, _ in states)
    for i, (x, y) in enumerate(coords):
        if atoms is None:
            c.dot(x, y, "figNavy", 0.045)
            if node_numbers:
                c.text(x, y - 0.19, str(i + 1), "synsmall")
            continue
        atom = atoms[i]
        element = atom["element"]
        if element == "C":
            continue  # skeletal carbon: vertex or bond end, as in Chapter 10
        h = atom["hydrogens"] if not paired else 0
        text = (
            element
            + ("H" if h else "")
            + (rf"\ensuremath{{_{{{h}}}}}" if h > 1 else "")
        )
        if element == "Cl" and h == 1:
            text = "HCl"
            if len(hcl) == 2 and active_atoms is None:
                if i == hcl[1]:
                    continue
                x = sum(coords[j][0] for j in hcl) / 2
                y = sum(coords[j][1] for j in hcl) / 2
                text = r"\textcolor{figInk}{2\,H}Cl"
        opacity = ',opacity=.23' if active_atoms is not None and i not in active_atoms else ''
        c.text(x, y, text, f"synchem,text=chem{element}"+opacity)
    for i, (name, dx, dy) in (ids or {}).items():
        x, y = coords[i]
        color = "npgBlue" if name == "a" else "npgPurple"
        c.text(x + dx, y + dy, name, f"synidx,text={color}")


def edges(matrix):
    return [
        (i, j, matrix[i][j], matrix[i][j])
        for i, j in combinations(range(len(matrix)), 2)
        if matrix[i][j]
    ]


def shift(coords, x, y, scale=1):
    return [(x + a * scale, y + b * scale) for a, b in coords]


